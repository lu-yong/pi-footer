#!/usr/bin/env node
// Bundles src/ into dist/ so pi loads a handful of files instead of resolving the whole
// source graph through jiti on every start.
//
//   node scripts/build.mjs          write dist/
//   node scripts/build.mjs --check  fail if the committed dist/ differs from a fresh build

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outdir = join(root, "dist");

// Supplied by pi at runtime. Bundling a copy would give the extension its own instances.
const HOST_PACKAGES = [
  "@earendil-works/pi-ai",
  "@earendil-works/pi-agent-core",
  "@earendil-works/pi-coding-agent",
  "@earendil-works/pi-tui",
  "typebox",
];
// Modules that must stay behind the dynamic import in src/index.ts.
const LAZY_SOURCES = /^src\/ui(\/|\.ts$)/u;

const BANNER = [
  "// @generated by scripts/build.mjs from src/ — do not edit; run `npm run build`.",
  "// @ts-nocheck -- JavaScript with a .ts extension, so pi's jiti loader always maps the",
  "// pi peer imports to the running pi instead of importing a second copy natively.",
].join("\n");

// src/ui/title-bar.ts only reads the version. Inlining the whole manifest would make
// dist/ change on every unrelated package.json edit.
const packageVersionOnly = {
  name: "package-version-only",
  setup(pluginBuild) {
    pluginBuild.onLoad({ filter: /[\\/]package\.json$/ }, async (args) => {
      if (resolve(args.path) !== join(root, "package.json")) return undefined;
      const { version } = JSON.parse(await readFile(args.path, "utf8"));
      return { contents: JSON.stringify({ version }), loader: "json" };
    });
  },
};

async function bundle() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["src/index.ts"],
    outdir,
    entryNames: "index",
    chunkNames: "chunks/[name]-[hash]",
    outExtension: { ".js": ".ts" },
    bundle: true,
    splitting: true,
    format: "esm",
    platform: "node",
    target: "es2022",
    external: HOST_PACKAGES.flatMap((name) => [name, `${name}/*`]),
    banner: { js: BANNER },
    legalComments: "none",
    plugins: [packageVersionOnly],
    metafile: true,
    write: false,
    logLevel: "warning",
  });
  const files = new Map(
    result.outputFiles.map((file) => [
      relative(outdir, file.path).replaceAll("\\", "/"),
      file.text,
    ]),
  );
  validate(result.metafile, files);
  return files;
}

// Everything the entry reaches through static imports, i.e. what pi loads at startup.
function eagerOutputs(outputs) {
  const entry = Object.keys(outputs).find((path) => outputs[path].entryPoint === "src/index.ts");
  if (!entry) throw new Error("build produced no output for src/index.ts");
  const eager = new Set();
  const pending = [entry];
  while (pending.length > 0) {
    const path = pending.pop();
    if (eager.has(path)) continue;
    eager.add(path);
    for (const imported of outputs[path].imports) {
      if (!imported.external && imported.kind !== "dynamic-import") pending.push(imported.path);
    }
  }
  return eager;
}

function validate(metafile, files) {
  const { outputs } = metafile;
  const eager = eagerOutputs(outputs);
  for (const path of eager) {
    const lazy = Object.keys(outputs[path].inputs).filter((input) => LAZY_SOURCES.test(input));
    if (lazy.length > 0) {
      throw new Error(`config UI leaked into the startup graph via ${path}: ${lazy.join(", ")}`);
    }
  }
  if (eager.size === Object.keys(outputs).length) {
    throw new Error("build produced no lazy chunk; the config UI is loaded at startup");
  }
  for (const [path, output] of Object.entries(outputs)) {
    for (const imported of output.imports) {
      if (imported.external) {
        const known =
          imported.path.startsWith("node:") || HOST_PACKAGES.some((name) => imported.path === name);
        if (!known) throw new Error(`unexpected external import in ${path}: ${imported.path}`);
      } else if (!files.has(relative("dist", imported.path))) {
        throw new Error(`${path} imports ${imported.path}, which was not emitted`);
      }
    }
  }
}

async function listFiles(directory, prefix = "") {
  let entries;
  try {
    entries = await readdir(join(directory, prefix), { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }
  const files = [];
  for (const entry of entries) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await listFiles(directory, path)));
    else files.push(path);
  }
  return files;
}

async function check(files) {
  const existing = await listFiles(outdir);
  const problems = [];
  for (const path of existing) {
    if (!files.has(path)) problems.push(`stale:   dist/${path}`);
  }
  for (const [path, text] of files) {
    if (!existing.includes(path)) problems.push(`missing: dist/${path}`);
    else if ((await readFile(join(outdir, path), "utf8")) !== text) {
      problems.push(`differs: dist/${path}`);
    }
  }
  if (problems.length === 0) return;
  console.error(`dist/ is out of date with src/:\n  ${problems.join("\n  ")}`);
  console.error("Run `npm run build` and commit dist/.");
  process.exitCode = 1;
}

async function write(files) {
  await rm(outdir, { recursive: true, force: true });
  for (const [path, text] of files) {
    await mkdir(dirname(join(outdir, path)), { recursive: true });
    await writeFile(join(outdir, path), text);
  }
  for (const [path, text] of files) {
    console.log(`${(text.length / 1024).toFixed(1).padStart(7)} KB  dist/${path}`);
  }
}

const files = await bundle();
if (process.argv.includes("--check")) await check(files);
else await write(files);
